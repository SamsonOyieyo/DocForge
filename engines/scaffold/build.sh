#!/usr/bin/env bash
# Pipeline smoke test.
#
# Produces a tiny package with exactly the layout the release workflow and
# `EngineManager` expect, so the whole chain (zip -> SHA-256 -> manifest ->
# release -> seed extraction -> hot-swap) can be exercised without compiling a
# real engine. Remove `scaffold` from engines/engines.json once a real engine
# is wired up.
#
# Usage: build.sh <target> <outdir>
set -euo pipefail

target="${1:?usage: build.sh <target> <outdir>}"
out="${2:?usage: build.sh <target> <outdir>}"
version="${ENGINE_VERSION:-0.0.0}"

rm -rf "$out"
mkdir -p "$out/bin" "$out/share"

cat > "$out/bin/scaffold" <<EOF
#!/bin/sh
# Generated by engines/scaffold/build.sh for $target.
echo "scaffold $version ($target)"
EOF
chmod 755 "$out/bin/scaffold"

printf 'engine=scaffold\nversion=%s\ntarget=%s\n' "$version" "$target" \
  > "$out/share/scaffold.txt"

cat > "$out/NOTICE" <<'EOF'
DocForge engine scaffold.
This package exists to test packaging, publishing and hot-swapping.
It is not a document engine.
EOF

echo "Staged scaffold $version for $target in $out"
