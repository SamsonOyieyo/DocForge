#!/usr/bin/env python3
"""Keep DocForge's version numbers in lockstep.

DocForge uses semantic versions with a Flutter build number:

    1.0.0  first public Windows release
    1.0.1  patch / bug-fix release
    1.1.0  feature release

The version lives in three places, and this script updates all of them:

    pubspec.yaml                  version: <version>+<build>
    lib/core/app_info.dart        static const String version = '<version>';
    installer/docforge.iss        #define MyAppVersion "<version>"

The Windows executable metadata is generated by Flutter from pubspec.yaml, so
it follows automatically. ``test/app_info_test.dart`` and
``tool/package_windows.ps1`` fail when the three sources disagree.

Usage:
    python tool/bump_version.py 1.0.1
    python tool/bump_version.py 1.1.0 --build 12
    python tool/bump_version.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent.parent
PUBSPEC = ROOT / "pubspec.yaml"
APP_INFO = ROOT / "lib" / "core" / "app_info.dart"
INSTALLER = ROOT / "installer" / "docforge.iss"

VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
PUBSPEC_RE = re.compile(r"(?m)^version:\s*(\d+\.\d+\.\d+)\+(\d+)\s*$")
APP_INFO_RE = re.compile(r"(static const String version = ')([^']+)(';)")
INSTALLER_RE = re.compile(r'(#define MyAppVersion ")([^"]+)(")')


def fail(message: str) -> NoReturn:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def read_version(path: Path, pattern: re.Pattern[str], label: str) -> str:
    match = pattern.search(path.read_text(encoding="utf-8"))
    if not match:
        fail(f"could not find {label} in {path.relative_to(ROOT)}")
    return match.group(2)


def check() -> int:
    pubspec = PUBSPEC.read_text(encoding="utf-8")
    match = PUBSPEC_RE.search(pubspec)
    if not match:
        fail("could not find `version: x.y.z+n` in pubspec.yaml")
    pubspec_version = match.group(1)
    build = match.group(2)

    app_info_version = read_version(APP_INFO, APP_INFO_RE, "AppInfo.version")
    installer_version = read_version(
        INSTALLER, INSTALLER_RE, 'the MyAppVersion fallback'
    )

    print(f"pubspec.yaml            {pubspec_version}+{build}")
    print(f"lib/core/app_info.dart  {app_info_version}")
    print(f"installer/docforge.iss  {installer_version}")

    versions = {pubspec_version, app_info_version, installer_version}
    if len(versions) != 1:
        print(
            "error: version sources disagree; run "
            "`python tool/bump_version.py <version>`",
            file=sys.stderr,
        )
        return 1

    print("ok: all version sources agree")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Bump DocForge's version in pubspec, Dart and the installer."
    )
    parser.add_argument(
        "version",
        nargs="?",
        help="new version (major.minor.patch), for example 1.0.1",
    )
    parser.add_argument(
        "--build",
        type=int,
        help="Flutter build number (defaults to the current build + 1)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="only verify that the version sources agree",
    )
    args = parser.parse_args()

    if args.check:
        return check()
    if not args.version:
        parser.error("provide a version or use --check")

    new_version = args.version.strip().lstrip("vV")
    if not VERSION_RE.match(new_version):
        fail(f"'{args.version}' is not a major.minor.patch version")

    pubspec = PUBSPEC.read_text(encoding="utf-8")
    match = PUBSPEC_RE.search(pubspec)
    if not match:
        fail("could not find `version: x.y.z+n` in pubspec.yaml")
    old_version = match.group(1)
    old_build = int(match.group(2))

    new_tuple = tuple(int(part) for part in new_version.split("."))
    old_tuple = tuple(int(part) for part in old_version.split("."))
    if new_tuple <= old_tuple:
        fail(
            f"new version {new_version} must be greater than "
            f"the current {old_version}"
        )

    new_build = args.build if args.build is not None else old_build + 1
    if new_build <= old_build:
        fail(f"build number {new_build} must be greater than {old_build}")

    pubspec = PUBSPEC_RE.sub(
        f"version: {new_version}+{new_build}", pubspec, count=1
    )
    PUBSPEC.write_text(pubspec, encoding="utf-8")

    app_info = APP_INFO.read_text(encoding="utf-8")
    app_info, count = APP_INFO_RE.subn(
        rf"\g<1>{new_version}\g<3>", app_info, count=1
    )
    if count != 1:
        fail("could not update AppInfo.version in lib/core/app_info.dart")
    APP_INFO.write_text(app_info, encoding="utf-8")

    installer = INSTALLER.read_text(encoding="utf-8")
    installer, count = INSTALLER_RE.subn(
        rf'\g<1>{new_version}\g<3>', installer, count=1
    )
    if count != 1:
        fail("could not update MyAppVersion in installer/docforge.iss")
    INSTALLER.write_text(installer, encoding="utf-8")

    print(f"{old_version}+{old_build} -> {new_version}+{new_build}")
    print("Updated pubspec.yaml, lib/core/app_info.dart and installer/docforge.iss")
    print("Next: update docs/CHANGELOG or notes, run tests, commit, tag "
          f"v{new_version}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
